const { neon } = require('neon-serverless');
const { writeFileSync } = require('node:fs');
const { dirname, join } = require('node:path');

const url = process.env['DATABASE_URL'];
if (!url) throw new Error('DATABASE_URL required');

const sql = neon(url);

(async () => {
  const tables = await sql`
    SELECT c.table_name, c.column_name, c.data_type, c.udt_name, c.is_nullable, c.column_default, c.is_identity
    FROM information_schema.columns c
    JOIN information_schema.tables t
      ON c.table_schema = t.table_schema AND c.table_name = t.table_name
    WHERE c.table_schema = 'public' AND t.table_type = 'BASE TABLE'
    ORDER BY c.table_name, c.ordinal_position
  `;

  const enums = await sql`
    SELECT t.typname AS name, e.enumlabel AS value, e.enumsortorder AS ord
    FROM pg_type t
    JOIN pg_enum e ON t.oid = e.enumtypid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
    ORDER BY t.typname, e.enumsortorder
  `;

  const typeMap = {
    integer: 'number',
    bigint: 'number',
    smallint: 'number',
    numeric: 'string',
    decimal: 'string',
    real: 'number',
    double_precision: 'number',
    boolean: 'boolean',
    text: 'string',
    varchar: 'string',
    'character varying': 'string',
    uuid: 'string',
    json: 'unknown',
    jsonb: 'unknown',
    'timestamp without time zone': 'Date',
    'timestamp with time zone': 'Date',
    timestamptz: 'Date',
    timestamp: 'Date',
  };

  const byEnum = {};
  for (const e of enums) {
    if (!byEnum[e.name]) byEnum[e.name] = [];
    byEnum[e.name].push(e.value);
  }

  for (const et of Object.keys(byEnum)) {
    typeMap[et] = et;
  }

  const byTable = {};
  for (const c of tables) {
    if (!byTable[c.table_name]) byTable[c.table_name] = [];
    byTable[c.table_name].push(c);
  }

  let out = `// Generated by gen-types.cjs — do not edit.\n`;
  out += `import type { ColumnType } from 'kysely';\n\n`;

  for (const [ename, members] of Object.entries(byEnum)) {
    out += `export type ${ename} = ${members.map(m => `'${m}'`).join(' | ')};\n`;
  }
  out += '\n';

  out += `export interface Database {\n`;
  for (const [tname, cols] of Object.entries(byTable)) {
    out += `  ${tname}: {\n`;
    for (const c of cols) {
      let t = typeMap[c.data_type] || 'unknown';
      if (byEnum[c.data_type]) t = byEnum[c.data_type].map(m => `'${m}'`).join(' | ');
      if (byEnum[c.udt_name]) t = byEnum[c.udt_name].map(m => `'${m}'`).join(' | ');

      // Select type, insert type, update type.
      let sel = t;
      let ins = t;
      let upd = t;
      if (c.is_nullable === 'YES') {
        ins = `${t} | null`;
        upd = `${t} | null`;
      }
      if (c.is_identity === 'YES') {
        // GENERATED ALWAYS AS IDENTITY — never provided by the app.
        ins = 'never';
        upd = 'never';
      } else if (c.column_default != null) {
        // Database-generated (default) — optional on insert.
        ins = `${ins} | undefined`;
      }
      out += `    ${c.column_name}: ColumnType<${sel}, ${ins}, ${upd}>;\n`;
    }
    out += `  };\n`;
  }
  out += `}\n`;

  const outPath = join(dirname(__filename), '..', 'src', 'prisma', 'types.ts');
  writeFileSync(outPath, out);
  console.log(out);
})();